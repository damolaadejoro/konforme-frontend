import jsPDF from 'jspdf'
import autoTable from 'jspdf-autotable'
import { Control, ComplianceScore, ArticleArea } from '../types/controls'
import { format } from 'date-fns'
import { getPDFStrings } from './pdfTranslations'

// Extend jsPDF type to include autoTable
declare module 'jspdf' {
  interface jsPDF {
    lastAutoTable: {
      finalY: number
    }
  }
}

interface PDFData {
  companyName: string
  complianceScore: ComplianceScore
  controls: Control[]
  articleAreas: ArticleArea[]
  criticalGaps: Pick<Control, 'title' | 'severity' | 'article'>[]
}

// Brand colors
const COLORS = {
  navy: '#0B1F3A',
  cyan: '#00C2D4',
  white: '#FFFFFF',
  lightGray: '#F3F4F6',
  darkGray: '#6B7280',
  red: '#EF4444',
  yellow: '#F59E0B',
  emerald: '#10B981',
  orange: '#F97316'
}

// Status colors
const getStatusColor = (status: string): string => {
  switch (status) {
    case 'Implemented': return COLORS.emerald
    case 'Partial': return COLORS.yellow
    case 'Planned': return COLORS.orange
    case 'Not Started': return COLORS.red
    default: return COLORS.darkGray
  }
}

// Get score color
const getScoreColor = (score: number): string => {
  if (score >= 75) return COLORS.emerald
  if (score >= 50) return COLORS.yellow
  return COLORS.red
}

// Add header to page
const addHeader = (doc: jsPDF, pageNumber: number) => {
  if (pageNumber === 1) return // No header on cover page

  doc.setFillColor(COLORS.navy)
  doc.rect(0, 0, doc.internal.pageSize.width, 20, 'F')

  // Logo/brand
  doc.setFontSize(12)
  doc.setTextColor(COLORS.cyan)
  doc.setFont('helvetica', 'bold')
  doc.text('⚡ Konforme', 14, 13)

  // Page number
  doc.setFontSize(9)
  doc.setTextColor(COLORS.white)
  doc.text(`Page ${pageNumber}`, doc.internal.pageSize.width - 14, 13, { align: 'right' })
}

// Add footer to page
const addFooter = (doc: jsPDF, t: ReturnType<typeof getPDFStrings>, isLastPage = false) => {
  const pageHeight = doc.internal.pageSize.height

  doc.setFontSize(8)
  doc.setTextColor(COLORS.darkGray)

  if (isLastPage) {
    doc.text(`${t.footerText} ${t.footerVisit}`, 14, pageHeight - 10)
  } else {
    doc.text(`${t.footerGeneratedOn} ${format(new Date(), 'MMMM d, yyyy')}`, 14, pageHeight - 10)
  }
}

export async function generateComplianceReport(data: PDFData, lang: string = 'en'): Promise<void> {
  const t = getPDFStrings(lang)
  const doc = new jsPDF()
  const pageWidth = doc.internal.pageSize.width
  const pageHeight = doc.internal.pageSize.height
  let pageNumber = 1

  // ===================
  // PAGE 1: Cover Page
  // ===================

  // Background
  doc.setFillColor(COLORS.navy)
  doc.rect(0, 0, pageWidth, pageHeight, 'F')

  // Shield/Logo - Simple representation
  doc.setFillColor(COLORS.cyan)
  doc.circle(pageWidth / 2, 50, 20, 'F')
  doc.setTextColor(COLORS.navy)
  doc.setFontSize(24)
  doc.setFont('helvetica', 'bold')
  doc.text('⚡', pageWidth / 2, 55, { align: 'center' })

  // Title
  doc.setTextColor(COLORS.white)
  doc.setFontSize(32)
  doc.setFont('helvetica', 'bold')
  doc.text(t.coverTitle, pageWidth / 2, 95, { align: 'center' })

  // Subtitle
  doc.setFontSize(16)
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(COLORS.cyan)
  doc.text(t.coverSubtitle, pageWidth / 2, 110, { align: 'center' })

  // Company name
  doc.setFontSize(20)
  doc.setTextColor(COLORS.white)
  doc.setFont('helvetica', 'bold')
  doc.text(data.companyName, pageWidth / 2, 140, { align: 'center' })

  // Report date
  doc.setFontSize(12)
  doc.setTextColor(COLORS.darkGray)
  doc.setFont('helvetica', 'normal')
  doc.text(`${t.coverReportDate} ${format(new Date(), 'MMMM d, yyyy')}`, pageWidth / 2, 160, { align: 'center' })

  // Generated by
  doc.setFontSize(10)
  doc.text(`${t.coverGeneratedBy}`, pageWidth / 2, 200, { align: 'center' })
  doc.setTextColor(COLORS.cyan)
  doc.setFont('helvetica', 'bold')
  doc.text(t.coverPlatformName, pageWidth / 2, 208, { align: 'center' })
  doc.setTextColor(COLORS.white)
  doc.setFont('helvetica', 'normal')
  doc.text('konforme.io', pageWidth / 2, 216, { align: 'center' })

  // =============================
  // PAGE 2: Executive Summary
  // =============================

  doc.addPage()
  pageNumber++
  addHeader(doc, pageNumber)

  let yPos = 35

  // Title
  doc.setTextColor(COLORS.navy)
  doc.setFontSize(24)
  doc.setFont('helvetica', 'bold')
  doc.text(t.execSummaryHeading, 14, yPos)
  yPos += 15

  // Overall Score - Large
  const scoreColor = getScoreColor(data.complianceScore.overall)
  doc.setFillColor(scoreColor)
  doc.roundedRect(14, yPos, 80, 40, 3, 3, 'F')
  doc.setTextColor(COLORS.white)
  doc.setFontSize(36)
  doc.setFont('helvetica', 'bold')
  doc.text(`${data.complianceScore.overall}%`, 54, yPos + 20, { align: 'center' })
  doc.setFontSize(12)
  doc.setFont('helvetica', 'normal')
  doc.text(t.execOverallReadiness, 54, yPos + 32, { align: 'center' })
  yPos += 50

  // Score Breakdown Table
  doc.setFontSize(14)
  doc.setTextColor(COLORS.navy)
  doc.setFont('helvetica', 'bold')
  doc.text(t.execScoreBreakdown, 14, yPos)
  yPos += 5

  const getStatusText = (score: number) =>
    score >= 75 ? t.execStatusGood : score >= 50 ? t.execStatusAtRisk : t.execStatusCritical

  autoTable(doc, {
    startY: yPos,
    head: [[t.execCategory, t.execScore, t.execStatus]],
    body: [
      [t.catTechnical, `${data.complianceScore.technical}%`, getStatusText(data.complianceScore.technical)],
      [t.catOrganizational, `${data.complianceScore.organizational}%`, getStatusText(data.complianceScore.organizational)],
      [t.catPeople, `${data.complianceScore.people}%`, getStatusText(data.complianceScore.people)],
    ],
    theme: 'grid',
    headStyles: { fillColor: COLORS.navy, textColor: COLORS.white, fontStyle: 'bold' },
    styles: { fontSize: 10, cellPadding: 5 },
    columnStyles: {
      0: { cellWidth: 80 },
      1: { cellWidth: 40, halign: 'center' },
      2: { cellWidth: 60, halign: 'center' }
    }
  })

  yPos = doc.lastAutoTable.finalY + 10

  // Control Status Summary
  const totalControls = data.controls.length || 1 // Avoid division by zero
  const implemented = data.controls.filter(c => c.status === 'Implemented').length
  const partial = data.controls.filter(c => c.status === 'Partial').length
  const planned = data.controls.filter(c => c.status === 'Planned').length
  const notStarted = data.controls.filter(c => c.status === 'Not Started').length

  doc.setFontSize(14)
  doc.setTextColor(COLORS.navy)
  doc.setFont('helvetica', 'bold')
  doc.text(t.controlStatusHeading, 14, yPos)
  yPos += 5

  autoTable(doc, {
    startY: yPos,
    head: [[t.controlStatusStatus, t.controlStatusCount, t.controlStatusPercentage]],
    body: [
      [t.controlImplemented, implemented.toString(), `${Math.round((implemented / totalControls) * 100)}%`],
      [t.controlPartial, partial.toString(), `${Math.round((partial / totalControls) * 100)}%`],
      [t.controlPlanned, planned.toString(), `${Math.round((planned / totalControls) * 100)}%`],
      [t.controlNotStarted, notStarted.toString(), `${Math.round((notStarted / totalControls) * 100)}%`],
      [t.controlTotal, totalControls.toString(), '100%']
    ],
    theme: 'grid',
    headStyles: { fillColor: COLORS.navy, textColor: COLORS.white, fontStyle: 'bold' },
    styles: { fontSize: 10, cellPadding: 5 },
    columnStyles: {
      0: { cellWidth: 80 },
      1: { cellWidth: 40, halign: 'center' },
      2: { cellWidth: 60, halign: 'center' }
    },
    didParseCell: (data) => {
      if (data.row.index === 4 && data.section === 'body') {
        data.cell.styles.fontStyle = 'bold'
        data.cell.styles.fillColor = COLORS.lightGray
      }
    }
  })

  yPos = doc.lastAutoTable.finalY + 10

  // Critical Gaps
  doc.setFontSize(11)
  doc.setTextColor(COLORS.navy)
  doc.setFont('helvetica', 'bold')
  doc.text(`${t.criticalGapsIdentified} ${data.criticalGaps.length}`, 14, yPos)
  yPos += 8

  // Executive Summary Text
  doc.setFontSize(10)
  doc.setTextColor(COLORS.darkGray)
  doc.setFont('helvetica', 'normal')
  const score = data.complianceScore.overall
  const summaryText = score >= 91 ? t.execExcellent
    : score >= 71 ? t.execGood
    : score >= 41 ? t.execModerate
    : t.execCritical
  const splitSummary = doc.splitTextToSize(summaryText, pageWidth - 28)
  doc.text(splitSummary, 14, yPos)

  addFooter(doc, t)

  // =================================
  // PAGE 3: Article 21 Coverage Map
  // =================================

  doc.addPage()
  pageNumber++
  addHeader(doc, pageNumber)

  yPos = 35

  doc.setTextColor(COLORS.navy)
  doc.setFontSize(24)
  doc.setFont('helvetica', 'bold')
  doc.text(t.coverageTitle, 14, yPos)
  yPos += 5

  doc.setFontSize(10)
  doc.setFont('helvetica', 'normal')
  doc.setTextColor(COLORS.darkGray)
  doc.text(t.coverageSubtitle, 14, yPos + 5)
  yPos += 15

  autoTable(doc, {
    startY: yPos,
    head: [[t.coverageArticle, t.coverageRequirement, t.coverageStatus, t.coverageProgress, t.coverageMaturity]],
    body: data.articleAreas.map(area => [
      area.article,
      area.name,
      area.status,
      `${area.implementedCount}/${area.controlCount}`,
      `${area.controlCount > 0 ? Math.round((area.implementedCount / area.controlCount) * 100) : 0}%`
    ]),
    theme: 'grid',
    headStyles: { fillColor: COLORS.navy, textColor: COLORS.white, fontStyle: 'bold', fontSize: 9 },
    styles: { fontSize: 9, cellPadding: 4 },
    columnStyles: {
      0: { cellWidth: 25, fontStyle: 'bold' },
      1: { cellWidth: 70 },
      2: { cellWidth: 30, halign: 'center' },
      3: { cellWidth: 25, halign: 'center' },
      4: { cellWidth: 25, halign: 'center' }
    },
    didParseCell: (data) => {
      if (data.column.index === 2 && data.section === 'body') {
        const status = data.cell.text[0]
        data.cell.styles.textColor = getStatusColor(status)
        data.cell.styles.fontStyle = 'bold'
      }
    }
  })

  addFooter(doc, t)

  // ===================================
  // PAGE 4+: Controls Detail (by area)
  // ===================================

  // Group controls by article area
  const controlsByArea: Record<string, Control[]> = {}
  data.controls.forEach(control => {
    if (!controlsByArea[control.articleArea]) {
      controlsByArea[control.articleArea] = []
    }
    controlsByArea[control.articleArea].push(control)
  })

  // Sort areas
  const sortedAreas = Object.keys(controlsByArea).sort()

  for (const areaName of sortedAreas) {
    const areaControls = controlsByArea[areaName]

    doc.addPage()
    pageNumber++
    addHeader(doc, pageNumber)

    yPos = 35

    // Area title
    doc.setTextColor(COLORS.navy)
    doc.setFontSize(18)
    doc.setFont('helvetica', 'bold')
    doc.text(areaName, 14, yPos)
    yPos += 10

    // Controls table
    const controlRows = areaControls.map(control => {
      const evidenceCount = control.evidence.length
      const evidenceText = evidenceCount > 0
        ? `${evidenceCount} ${evidenceCount > 1 ? t.detailFiles : t.detailFile}`
        : t.detailNone

      return [
        control.title,
        control.article,
        control.status,
        control.owner || t.detailUnassigned,
        control.dueDate ? format(new Date(control.dueDate), 'MMM d, yyyy') : t.detailNoDate,
        evidenceText
      ]
    })

    autoTable(doc, {
      startY: yPos,
      head: [[t.detailControl, t.detailArticle, t.detailStatus, t.detailOwner, t.detailDueDate, t.detailEvidence]],
      body: controlRows,
      theme: 'grid',
      headStyles: { fillColor: COLORS.navy, textColor: COLORS.white, fontStyle: 'bold', fontSize: 8 },
      styles: { fontSize: 8, cellPadding: 3 },
      columnStyles: {
        0: { cellWidth: 60 },
        1: { cellWidth: 25, fontSize: 7 },
        2: { cellWidth: 25, halign: 'center' },
        3: { cellWidth: 30 },
        4: { cellWidth: 25, halign: 'center', fontSize: 7 },
        5: { cellWidth: 20, halign: 'center', fontSize: 7 }
      },
      didParseCell: (data) => {
        if (data.column.index === 2 && data.section === 'body') {
          const status = data.cell.text[0]
          data.cell.styles.textColor = getStatusColor(status)
          data.cell.styles.fontStyle = 'bold'
        }
        // Highlight gaps
        if (data.section === 'body') {
          const status = controlRows[data.row.index][2]
          if (status === 'Not Started' || status === 'Planned') {
            data.cell.styles.fillColor = '#FEF3C7' // Light yellow
          }
        }
      }
    })

    addFooter(doc, t)
  }

  // ============================
  // FINAL PAGE: Recommendations
  // ============================

  doc.addPage()
  pageNumber++
  addHeader(doc, pageNumber)

  yPos = 35

  doc.setTextColor(COLORS.navy)
  doc.setFontSize(24)
  doc.setFont('helvetica', 'bold')
  doc.text(t.recsHeading, 14, yPos)
  yPos += 15

  // Get top gaps (Not Started controls)
  const gaps = data.controls
    .filter(c => c.status === 'Not Started')
    .sort((a, b) => {
      const severityOrder: Record<string, number> = { critical: 0, high: 1, medium: 2 }
      return (severityOrder[a.severity] ?? 3) - (severityOrder[b.severity] ?? 3)
    })
    .slice(0, 10)

  if (gaps.length === 0) {
    doc.setFontSize(12)
    doc.setTextColor(COLORS.emerald)
    doc.text(t.recsNoGapsTitle, 14, yPos)
    doc.setFontSize(10)
    doc.setTextColor(COLORS.darkGray)
    doc.text(t.recsNoGapsBody, 14, yPos + 8)
  } else {
    doc.setFontSize(11)
    doc.setTextColor(COLORS.darkGray)
    doc.setFont('helvetica', 'normal')
    doc.text(t.recsGapsIntro, 14, yPos)
    yPos += 10

    gaps.forEach((control, index) => {
      if (yPos > pageHeight - 40) {
        doc.addPage()
        pageNumber++
        addHeader(doc, pageNumber)
        yPos = 35
      }

      // Gap number
      doc.setFillColor(COLORS.cyan)
      doc.circle(18, yPos - 1, 3, 'F')
      doc.setTextColor(COLORS.white)
      doc.setFontSize(9)
      doc.setFont('helvetica', 'bold')
      doc.text(`${index + 1}`, 18, yPos + 1, { align: 'center' })

      // Control title
      doc.setTextColor(COLORS.navy)
      doc.setFontSize(11)
      doc.setFont('helvetica', 'bold')
      doc.text(control.title, 24, yPos)

      // Article and severity
      doc.setFontSize(9)
      doc.setFont('helvetica', 'normal')
      doc.setTextColor(COLORS.darkGray)
      doc.text(`${control.article} • ${control.severity.toUpperCase()} severity`, 24, yPos + 5)

      // Recommended action
      doc.setFontSize(9)
      doc.setTextColor(COLORS.darkGray)
      const splitAction = doc.splitTextToSize(t.recsAction, pageWidth - 38)
      doc.text(splitAction, 24, yPos + 10)

      yPos += 20
    })
  }

  // Final footer
  yPos = pageHeight - 30
  doc.setDrawColor(COLORS.cyan)
  doc.setLineWidth(0.5)
  doc.line(14, yPos, pageWidth - 14, yPos)
  yPos += 10

  doc.setFontSize(10)
  doc.setTextColor(COLORS.darkGray)
  doc.setFont('helvetica', 'normal')
  doc.text(t.footerText, 14, yPos)
  doc.setTextColor(COLORS.cyan)
  doc.setFont('helvetica', 'bold')
  doc.text(t.footerVisit, 14, yPos + 6)

  // Save the PDF
  const filename = `${t.filenamePrefix}-${format(new Date(), 'yyyy-MM-dd')}.pdf`
  doc.save(filename)
}
